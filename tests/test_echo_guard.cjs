/* Text echo matching is a conservative heuristic, not acoustic speaker identity. */
const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('hologram/ui/index.html','utf8');
const code=html.split('// ECHO_GUARD_BEGIN')[1].split('// ECHO_GUARD_END')[0];
const echo=vm.runInNewContext(`(()=>{${code};return likelyPlaybackEcho})()`);
assert.equal(echo('दिल्ली में', 'भारत में दिल्ली में मौसम अच्छा है।'),true);
assert.equal(echo('Hi, THERE!', 'Well, hi there. What next?'),true);
assert.equal(echo('open youtube', 'Please open youtube when ready.'),true);
assert.equal(echo('open youtube', 'Please do not open youtubers.'),false);
assert.equal(echo('', 'anything'),false);
assert.equal(echo('question', ''),false);
assert.equal(echo('weather in Mumbai', 'weather in Delhi'),false);
const reply='I can tell you the current weather in New Delhi right now';
assert.equal(echo('I can tell you the curent weather in New Delhi',reply),true);
assert.equal(echo('I can tell you the curent weather in New Delhi stop listening',reply),false);
assert.equal(echo('I can tell you the current weather in New York',reply),false);
const digits='Here is the forecast for Delhi tomorrow at 4 in the afternoon';
assert.equal(echo('Here is the forecast for Delhi tomorrow at 5 in the afternoon',digits),false);
const neg='I can not tell you the current weather for New Delhi';
assert.equal(echo('I can no tell you the current weather for New Delhi',neg),false);
console.log('PASS: normalized Hindi/English, bounded spelling tolerance, changed number, negation and new question');
